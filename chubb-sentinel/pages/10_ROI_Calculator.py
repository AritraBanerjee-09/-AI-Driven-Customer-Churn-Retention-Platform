# pages/10_ROI_Calculator.py
import streamlit as st
import pandas as pd

st.set_page_config(page_title="ROI Calculator", layout="wide")
st.title("Retention ROI Calculator")


with st.expander("View Key Assumptions & Placeholders for this Prototype"):
    st.caption("""
    This prototype makes several assumptions due to the absence of complete, real-world operational data. For a production system, these placeholders would be replaced with live data integrations.

    **Business Metrics (in ROI Calculator):**
    - **Average Customer Acquisition Cost (CAC):** Assumed to be **$500**. This is a user-configurable placeholder.
    - **Cost of Retention Action:** Assumed to be **$100**. This is a user-configurable placeholder.

   """)


if 'featured_data' not in st.session_state:
    st.error("Customer data not loaded. Please start from the main app page.")
    st.stop()

df = st.session_state['featured_data'].copy()

st.markdown("This tool helps quantify the financial impact of successfully retaining an at-risk customer.")

# --- Inputs ---
col1, col2 = st.columns(2)

with col1:
    st.subheader("Select a Customer")
    # Use high-risk customers for the selection
    high_risk_df = df[df['churn_probability'] > 0.5]
    customer_id = st.selectbox("Select an At-Risk Customer ID", high_risk_df['individual_id'])
    
    st.subheader("Define Costs")
    # Use a placeholder for CAC, as we can't calculate it
    cac = st.number_input("Average Customer Acquisition Cost (CAC)", value=500)
    retention_cost = st.number_input("Hypothetical Cost of Retention Action (e.g., discount, gift)", value=100)

# --- Calculation & Display ---
with col2:
    st.subheader("Financial Impact Analysis")
    if customer_id:
        customer_data = df[df['individual_id'] == customer_id].iloc[0]
        
        # Customer Annual Value (CAV) is their premium
        cav = customer_data['curr_ann_amt']
        
        # Calculate financial gain and ROI
        net_gain_from_retention = cav - retention_cost
        avoided_cost = cac # The cost of replacing them
        total_value = net_gain_from_retention + avoided_cost
        
        # Simplified ROI formula for this context
        roi = (total_value - retention_cost) / retention_cost * 100
        
        st.metric("Customer Annual Value (CAV)", f"${cav:,.2f}")
        st.metric("Net Gain from this Customer (Next Year)", f"${net_gain_from_retention:,.2f}")
        st.metric("Avoided Cost of Acquiring a Replacement", f"${avoided_cost:,.2f}")
        
        st.divider()
        
        st.metric("Total Value Generated by Retention Action", f"${total_value:,.2f}", 
                  help="This is the sum of the net gain and the avoided replacement cost.")
        st.metric("Return on Investment (ROI) of this Action", f"{roi:.1f}%",
                  help="For every dollar spent on retention, you get this much back in value.")